    "shopping-bag": ShoppingBag,
    "message-circle": MessageCircle,
    "electrical-services": Zap,
    "home-repair-service": Wrench,
    "precision-manufacturing": Cog,
    "inventory-2": Package,
    category: Tag,
    "support-agent": PhoneCall,
    "local-offer": Tag,
    public: Home,
    verified: BadgeCheck,
    science: Cog,
    whatsapp: MessageCircle,
    facebook: Users,
    "facebook-square": Users,
    "facebook-f": Users,
    instagram: MessageCircle,
    twitter: MessageCircle,
    telegram: MessageCircle,
    "telegram-plane": MessageCircle,
    "youtube-play": MessageCircle,
